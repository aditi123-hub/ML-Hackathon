"""Trip-grouped sampling, fitting, and scoring shared by all classifiers."""

import logging
from time import perf_counter

import numpy as np
from sklearn.metrics import f1_score, log_loss
from sklearn.model_selection import GroupKFold

from .metrics import evaluate


log = logging.getLogger("pathsnap.training")
NEAREST_NEGATIVES = 8


def fitting_rows(batches, max_observations, seed):
    """Sample whole eligible observations and retain spatially plausible negatives."""
    rng = np.random.default_rng(seed)
    features, labels = [], []
    for batch in batches:
        # Filter labels before drawing the seeded fit sample. Validation
        # evaluates whole trips with all observations, including weak labels.
        rows = np.arange(len(batch.reference_ids))
        if batch.fit_eligible is not None:
            rows = rows[batch.fit_eligible]
        if len(rows) > max_observations:
            # Bound the influence of very long trips and cap fit cost.
            rows = np.sort(rng.choice(rows, max_observations, replace=False))
        candidates = batch.candidate_ids[rows]
        target = candidates == batch.reference_ids[rows, None]
        # Keep the aligned positive even if it is outside the hard-negative
        # sample, provided it was already generated by the spatial lookup.
        keep = (candidates >= 0) & ((np.arange(candidates.shape[1]) < NEAREST_NEGATIVES) | target)
        features.append(batch.features[rows][keep])
        labels.append(target[keep])
    features, labels = np.concatenate(features), np.concatenate(labels)
    if len(np.unique(labels)) != 2:
        raise ValueError("The fit sample must contain both matching and nonmatching candidates.")
    return features, labels


def make_folds(batches, n_splits, max_observations, seed):
    identifiers = [batch.trip_id for batch in batches]
    folds = []
    # Keep all GPS observations and candidates from one trip in the same fold.
    for fit_indices, valid_indices in GroupKFold(n_splits=n_splits).split(identifiers, groups=identifiers):
        training = [batches[index] for index in fit_indices]
        validation = [batches[index] for index in valid_indices]
        folds.append((fitting_rows(training, max_observations, seed), validation))
    log.info("Prepared %d trip-grouped folds", len(folds))
    return folds


def fit(factory, params, sample, seed, label):
    """Fit one fresh estimator or scaling pipeline on the chosen fold."""
    features, labels = sample
    model = factory(seed, **params)
    classifier = model[-1] if hasattr(model, "steps") else model
    log.info("%s fitting %s candidates", label, f"{len(labels):,}")
    started = perf_counter()
    model.fit(features, labels)
    return model, classifier, perf_counter() - started


def cross_validate(factory, params, folds, seed, label):
    """Validate on completely held-out trips using the same fit policy each time."""
    outcomes = []
    for number, (sample, validation) in enumerate(folds, start=1):
        stage = f"{label} fold {number}/{len(folds)}"
        model, _, elapsed = fit(factory, params, sample, seed, stage)
        report = evaluate(model, validation)
        outcomes.append(report | {
            "training_s": elapsed,
            "training_rows": len(sample[1]),
            "validation_trips": [trip.trip_id for trip in validation],
        })
        log.info(
            "%s held-out top-1 %.2f%%, macro F1 %.2f%%, fit %.2fs, inference %.2fs",
            stage, 100 * report["top1"], 100 * report["macro_f1"], elapsed, report["inference_s"],
        )
    return {
        "folds": outcomes,
        "mean_top1": float(np.mean([outcome["top1"] for outcome in outcomes])),
        "mean_macro_f1": float(np.mean([outcome["macro_f1"] for outcome in outcomes])),
    }


def fit_and_compare(factory, params, sample, testing, seed, label):
    """Refit on all permitted training trips and record student-test comparison."""
    model, classifier, elapsed = fit(factory, params, sample, seed, f"{label} full fit")
    features, labels = sample
    probabilities = model.predict_proba(features)[:, 1]
    report = evaluate(model, testing)
    log.info(
        "%s student-test top-1 %.2f%%, macro F1 %.2f%%, fit %.2fs",
        label, 100 * report["top1"], 100 * report["macro_f1"], elapsed,
    )
    return model, {
        "configuration": classifier.get_params(),
        "training_s": elapsed,
        "training_rows": len(labels),
        "fit_macro_f1": float(f1_score(labels, probabilities >= 0.5, average="macro")),
        "fit_log_loss": float(log_loss(labels, probabilities)),
        "student_test": report,
        "loss_curve": getattr(classifier, "loss_curve_", []),
    }
